-- 1. Extend assessments table for clarification loop & evidence
alter table public.assessments
  add column if not exists recommendations jsonb not null default '[]'::jsonb,
  add column if not exists clarification_questions jsonb not null default '[]'::jsonb,
  add column if not exists evidence jsonb not null default '{}'::jsonb;

-- 2. Extend reservations table for multi-service requests & quotes
alter table public.reservations
  add column if not exists service_type text not null default 'cold_storage',
  add column if not exists quote_amount numeric(10,2),
  add column if not exists quote_notes text,
  add column if not exists provider_notes text;

